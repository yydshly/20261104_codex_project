"""Reproduce product-flow checks with a real browser and explicit QA fixtures."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
URL = 'http://127.0.0.1:5267/'
report = {'checks': [], 'screenshots': [], 'runtimeErrors': [], 'browserWarnings': []}

def check(name, value=True, detail=None):
    assert value, name
    report['checks'].append({'name': name, 'passed': True, 'detail': detail})

def screenshot(page, name):
    page.screenshot(path=str(ROOT / 'evidence' / 'v2' / (name + '.png')))
    report['screenshots'].append(name + '.png')

def ready(page, suffix='?qa'):
    page.goto(URL + suffix)
    page.wait_for_function('window.__qa')
    page.wait_for_timeout(1700)
    page.wait_for_function('!document.querySelector("canvas").getContext("webgl2").isContextLost()')

def snapshot(page):
    return page.evaluate('__qa.snapshot()')

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={'width':1440,'height':900},device_scale_factor=1)
    page = context.new_page()
    page.on('pageerror', lambda error: report['runtimeErrors'].append(str(error)))
    page.on('console', lambda message: report['browserWarnings'].append(message.text) if message.type == 'warning' else None)
    ready(page)
    screenshot(page, 'product-title')
    check('title opens with a focused primary action', page.locator('#primary').evaluate('e=>e===document.activeElement'))
    page.locator('#primary').click()
    check('new campaign enters authored first-chapter briefing', snapshot(page)['phase']=='briefing')
    page.locator('#primary').click()
    page.wait_for_timeout(400)
    check('first gesture unlocks browser audio',snapshot(page)['audioState']=='running')
    page.wait_for_function('__qa.snapshot().soundBank.decodedSounds===10')
    check('four GLB models and both atlases load',snapshot(page)['assets']['modelsLoaded']==4 and snapshot(page)['assets']['atlasesLoaded']==2)
    check('ten generated sounds decode without error',snapshot(page)['soundBank']['error'] is None)
    page.evaluate('__qa.fixture("combat")')
    page.keyboard.press('q');page.wait_for_timeout(130)
    check('keyboard Q consumes energy and damages enemies',snapshot(page)['player']['energy']==0 and snapshot(page)['enemies'][0]['hp']==1)
    check('pulse drives a live flipbook and generated sound',snapshot(page)['assets']['activeFlipbooks']>0 and snapshot(page)['soundBank']['assetSoundEvents']>0)
    screenshot(page,'pulse')
    page.evaluate('__qa.fixture("idle")')
    check('chapter reset clears active flipbooks',snapshot(page)['assets']['activeFlipbooks']==0)
    initial = snapshot(page)['player']
    page.keyboard.down('d')
    page.wait_for_timeout(250)
    page.keyboard.up('d')
    check('keyboard movement updates the visible player', snapshot(page)['player']['x']>initial['x'])
    page.keyboard.press('Space')
    page.wait_for_timeout(100)
    check('dash uses its cooldown and records a player action',snapshot(page)['totals']['dashes']==1)
    page.locator('#pause').click()
    frozen = snapshot(page)
    page.wait_for_timeout(300)
    check('pause freezes simulation clock',snapshot(page)['time']==frozen['time'])
    page.locator('#settings-open').click()
    for _ in range(10): page.keyboard.press('Tab')
    check('native settings modal keeps keyboard focus inside',page.locator('#settings').evaluate('e=>e.contains(document.activeElement)'))
    page.locator('#motion-setting').check()
    page.locator('#quality-setting').select_option('low')
    page.locator('#settings-close').click()
    check('settings persist and return to paused screen',snapshot(page)['settings']['reduced'] and snapshot(page)['phase']=='paused')
    page.keyboard.press('p')
    check('pause resumes to gameplay',snapshot(page)['phase']=='playing')
    screenshot(page,'chapter1')
    page.evaluate('__qa.fixture("combat")')
    for _ in range(3):
        page.keyboard.press('j'); page.wait_for_timeout(470)
    check('normal keyboard attacks defeat a real enemy',snapshot(page)['enemies'][0]['hp']==0)
    check('defeated enemy creates one stable pickup',len(snapshot(page)['pickups'])==1)
    screenshot(page,'combat-feedback')
    latencies=snapshot(page)['renderSubmissionSamples']
    check('accepted attack inputs reach a submitted action frame',bool(latencies),{'samplesMs':latencies,'scope':'keydown handler to render() return, excludes hardware input/display latency'})
    page.evaluate('__qa.fixture("beacon")')
    page.keyboard.press('e')
    page.wait_for_function('__qa.snapshot().phase==="upgrade"')
    screenshot(page,'upgrade')
    page.locator('[data-upgrade="heart"]').click()
    check('one upgrade moves to the second chapter',snapshot(page)['chapter']==1 and snapshot(page)['upgrades']==['heart'])
    check('life upgrade affects gameplay stats',snapshot(page)['player']['hp']==8)
    page.reload(); page.wait_for_function('window.__qa')
    page.locator('#continue').click()
    check('reload continues from checkpoint with equipment',snapshot(page)['chapter']==1 and snapshot(page)['upgrades']==['heart'])
    page.locator('#primary').click()
    page.wait_for_timeout(1200)
    screenshot(page,'chapter2')
    page.evaluate('__qa.fixture("low-health")')
    page.wait_for_function('__qa.snapshot().phase==="lost"')
    screenshot(page,'failure')
    page.locator('#primary').click()
    check('loss retries a fresh chapter with cleared transient state',snapshot(page)['phase']=='briefing' and snapshot(page)['cores']==0 and len(snapshot(page)['projectiles'])==0)
    page.evaluate('__qa.fixture("timeout")')
    page.wait_for_function('__qa.snapshot().phase==="lost"')
    check('time expiry produces the timeout explanation',snapshot(page)['failure']=='time')
    page.evaluate('__qa.fixture("boss-phase",2)')
    page.wait_for_timeout(500)
    check('boss phase change is visible in the real HUD','第二阶段' in page.locator('#boss-phase').inner_text())
    screenshot(page,'chapter3')
    page.evaluate('__qa.fixture("beacon",2)')
    page.keyboard.press('e')
    page.wait_for_function('__qa.snapshot().phase==="won"')
    screenshot(page,'ending-fixture')
    check('ending writes a local best record',page.evaluate('JSON.parse(localStorage.getItem("tidelight.record.v1")).score')>0)
    page.evaluate('localStorage.setItem("tidelight.campaign.v1",JSON.stringify({version:999}))')
    page.reload();page.wait_for_function('window.__qa')
    check('unsupported save is rejected with a usable new-game entry',page.locator('#continue').is_hidden() and page.locator('#primary').is_visible())
    context.close()

    phone=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,device_scale_factor=1,reduced_motion='reduce')
    mobile=phone.new_page()
    mobile.on('pageerror',lambda error:report['runtimeErrors'].append(str(error)))
    ready(mobile)
    screenshot(mobile,'mobile-title')
    mobile.locator('#primary').tap();mobile.locator('#primary').tap()
    screenshot(mobile,'mobile-play')
    check('portrait page fits viewport',mobile.evaluate('document.documentElement.scrollWidth===innerWidth'))
    check('critical touch buttons are at least 44 CSS pixels',mobile.locator('#attack').bounding_box()['width']>=44 and mobile.locator('#dash').bounding_box()['height']>=44)
    client=phone.new_cdp_session(mobile)
    joystick=mobile.locator('#joystick').bounding_box()
    attack=mobile.locator('#attack').bounding_box()
    finger1={'x':joystick['x']+joystick['width']*.85,'y':joystick['y']+joystick['height']/2,'id':1}
    finger2={'x':attack['x']+attack['width']/2,'y':attack['y']+attack['height']/2,'id':2}
    before=snapshot(mobile)['player']['x']
    client.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[finger1]})
    client.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[finger1,finger2]})
    mobile.wait_for_timeout(300)
    check('multitouch accepts movement and held attack together',snapshot(mobile)['player']['x']>before and snapshot(mobile)['touch']['attack'])
    client.send('Input.dispatchTouchEvent',{'type':'touchCancel','touchPoints':[]})
    mobile.wait_for_timeout(200)
    check('touch cancellation clears every held input',snapshot(mobile)['touch']=={'x':0,'y':0,'attack':False})
    mobile.evaluate('__qa.fixture("idle")')
    mobile.locator('#pulse-button').tap();mobile.wait_for_timeout(100)
    check('mobile pulse button dispatches the same game action',snapshot(mobile)['totals']['pulses']==1)
    chapter=snapshot(mobile)['chapter']
    mobile.set_viewport_size({'width':844,'height':390})
    mobile.wait_for_timeout(300)
    screenshot(mobile,'mobile-landscape')
    check('orientation change preserves the campaign',snapshot(mobile)['chapter']==chapter and snapshot(mobile)['phase']=='playing')
    mobile.evaluate('window.dispatchEvent(new Event("blur"))')
    check('focus loss pauses safely',snapshot(mobile)['phase']=='paused')
    phone.close()

    blocked=browser.new_context(viewport={'width':1280,'height':800})
    blocked.add_init_script('Storage.prototype.setItem = function(){throw new DOMException("blocked","SecurityError")}')
    blocked_page=blocked.new_page();ready(blocked_page)
    blocked_page.locator('#primary').click()
    check('unavailable storage leaves the game playable and reports failure',not snapshot(blocked_page)['saveAvailable'] and snapshot(blocked_page)['phase']=='briefing')
    blocked.close();browser.close()

check('browser has no unhandled runtime errors',not report['runtimeErrors'])
report['passed']=len(report['checks'])
(ROOT/'evidence'/'v2'/'browser-verification.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),'utf-8')
print(json.dumps({'passed':report['passed'],'runtimeErrors':report['runtimeErrors'],'latency':latencies},ensure_ascii=False))
