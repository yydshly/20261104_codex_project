import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {briefDefaults,prompts,history,sources,materializePrompt} from '../src/research-content.js';
import {validatePageLinks,parseGlb} from './verify-warlord.mjs';
const root=fileURLToPath(new URL('..',import.meta.url));
const html=await fs.readFile(path.join(root,'research.html'),'utf8');
const exported=JSON.parse(await fs.readFile(path.join(root,'docs/character-prompts.json'),'utf8'));
assert.deepEqual(exported.prompts,prompts,'Download recipes match the displayed source');
assert.deepEqual(exported.history,history,'Historical excerpts match their separate export');
assert.deepEqual(exported.sources,sources);assert.deepEqual(exported.defaults,briefDefaults);
assert.equal(new Set(prompts.map(p=>p.id)).size,prompts.length);
const text=await fs.readFile(path.join(root,'docs/character-prompts.txt'),'utf8');
for(const prompt of prompts){assert(text.includes(materializePrompt(prompt.text)));assert(!materializePrompt(prompt.text).includes('{{'));}
assert.equal(exported.evidenceDate,'2026-11-12');assert.equal(exported.compiledAt,'2026-11-21');
const glb=parseGlb(await fs.readFile(path.join(root,'assets/warlord/warlord.glb')));
const high=JSON.parse(await fs.readFile(path.join(root,'assets/warlord/optimization.json'),'utf8'));
const benchmark=JSON.parse(await fs.readFile(path.join(root,'docs/warlord-benchmark-v5.json'),'utf8'));
const native=JSON.parse(await fs.readFile(path.join(root,'engine/warlord/validation/sourcekit-fresh-import.json'),'utf8'));
const metadata=JSON.parse(await fs.readFile(path.join(root,'assets/warlord/metadata.json'),'utf8'));
assert.equal(glb.document.animations.length,13);assert.equal(glb.document.skins[0].joints.length,100);
assert.equal(high.runtime.triangles,266728);assert(html.includes(high.runtime.triangles.toLocaleString('en-US')));
for(const lod of high.lods)assert(html.includes(lod.triangles.toLocaleString('en-US')));
assert.equal(benchmark.asset.sha256,metadata.sha256);assert.equal(native.assetSha256,metadata.sha256);
assert(html.includes(`${benchmark.browser.averageFps} FPS`));assert(html.includes(metadata.sha256));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(ids.length,new Set(ids).size);
const links=await validatePageLinks(root);
console.log(JSON.stringify({status:'passed',pages:links.pages.length,promptRecipes:prompts.length,historicalExcerpts:history.length,references:sources.length,downloadSourceIdentity:true,historicalEvidenceDate:exported.evidenceDate,assetSha256:metadata.sha256,scope:'Static links, recipe export identity and factual cross-checks against actual assets and saved evidence. Does not claim a new combat, GPU or art-quality test.'},null,2));
