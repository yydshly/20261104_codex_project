import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('../capability-elevator/node_modules/playwright');
const root = path.dirname(fileURLToPath(import.meta.url));
const local = process.argv[2];
const browser = await chromium.launch({ executablePath: '[本机路径已省略] Files/Google/Chrome/Application/chrome.exe', headless: true });
const checks = { story: 'Open the offline tea launch page, view existing motion, open/close films, choose a tea moment and download the visual.', new_generation_credits: 0, browser: 'isolated headless Chrome; no existing user browser or native UI controlled', console_errors: [], requests_failed: [] };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, acceptDownloads: true });
  const page = await context.newPage();
  page.on('pageerror', error => checks.console_errors.push(String(error)));
  page.on('requestfailed', request => checks.requests_failed.push({ url: request.url().slice(0, 160), error: request.failure()?.errorText }));
  const response = await page.goto(local || pathToFileURL(path.join(root, 'index.html')).href, { waitUntil: 'load' });
  if (local) assert.equal(response.status(), 200);
  await page.locator('#hero-film').evaluate(video => new Promise((resolve, reject) => {
    if (video.readyState >= 2) return resolve();
    video.addEventListener('loadeddata', resolve, { once: true });
    video.addEventListener('error', () => reject(new Error('hero media error')), { once: true });
  }));
  await page.waitForFunction(() => document.getElementById('hero-film').currentTime > .3);
  checks.desktop_media = await page.locator('#hero-film').evaluate(video => ({ currentTime: video.currentTime, duration: video.duration, width: video.videoWidth, height: video.videoHeight, muted: video.muted, error: video.error?.message || null }));
  assert.equal(checks.desktop_media.width, 1112);
  assert.equal(checks.desktop_media.height, 834);
  assert.equal(checks.desktop_media.muted, true);
  assert(Math.abs(checks.desktop_media.duration - 121/24) < .01);
  await page.locator('#hero-film').evaluate(video => video.pause());
  await page.screenshot({ path: path.join(root, 'reports/desktop-home.png') });
  await page.screenshot({ path: path.join(root, 'reports/desktop-page.png'), fullPage: true });
  await page.getByRole('button', { name: '看茶烟升起', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('dialog-film').currentTime > .1);
  assert(await page.locator('#film-dialog').evaluate(dialog => dialog.open));
  assert.equal(await page.locator('#dialog-film').evaluate(video => video.videoWidth), 1112);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#film-dialog').evaluate(dialog => dialog.open), false);
  assert.equal(await page.locator('#dialog-film').evaluate(video => video.paused), true);
  checks.teapot_dialog = 'playback, Escape close, pause and focus return passed';
  assert.equal(await page.evaluate(() => document.activeElement?.dataset.openFilm), 'teapot');
  await page.locator('#landscape').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.getElementById('landscape-film').currentTime > .1);
  assert.equal(await page.locator('#landscape-film').evaluate(video => video.videoWidth), 834);
  await page.getByRole('button', { name: '看一段山水', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('dialog-film').videoWidth === 834 && document.getElementById('dialog-film').currentTime > .1);
  await page.getByRole('button', { name: '关闭影像', exact: true }).click();
  checks.landscape = 'inline visibility playback, large film and close passed';
  await page.getByRole('tab', { name: '两人对谈', exact: true }).click();
  assert(await page.locator('#panel-together').isVisible());
  assert.equal(await page.locator('#panel-alone').isVisible(), false);
  await page.keyboard.press('ArrowRight');
  assert(await page.locator('#panel-guests').isVisible());
  assert.equal(await page.getByRole('tab', { name: '春日待客', exact: true }).getAttribute('aria-selected'), 'true');
  checks.ritual_tabs = 'click and ArrowRight keyboard selection passed';
  const pending = page.waitForEvent('download');
  await page.getByRole('link', { name: '保存春日图景', exact: false }).click();
  const download = await pending;
  assert.equal(download.suggestedFilename(), '山白-青山一盏-茶器主视觉.webp');
  assert.equal(await download.failure(), null);
  checks.download = { filename: download.suggestedFilename(), status: 'passed' };

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror', error => checks.console_errors.push(String(error)));
  await mobile.goto(pathToFileURL(path.join(root, 'index.html')).href, { waitUntil: 'load' });
  await mobile.locator('#hero-film').evaluate(video => video.pause());
  checks.mobile = await mobile.evaluate(() => ({ viewport: innerWidth, body: document.documentElement.scrollWidth, title: document.title, reduced_motion_paused: document.getElementById('hero-film').paused, external_dependencies: [...document.querySelectorAll('[src],[href],[poster]')].flatMap(element => ['src', 'href', 'poster'].map(attribute => element.getAttribute(attribute))).filter(value => value && /^https?:/.test(value)) }));
  assert.equal(checks.mobile.body, 390);
  assert.equal(checks.mobile.reduced_motion_paused, true);
  assert.deepEqual(checks.mobile.external_dependencies, []);
  await mobile.screenshot({ path: path.join(root, 'reports/mobile-home.png') });
  await mobile.screenshot({ path: path.join(root, 'reports/mobile-page.png'), fullPage: true });
  await mobile.getByRole('button', { name: '看茶烟升起', exact: true }).click();
  await mobile.waitForFunction(() => document.getElementById('dialog-film').currentTime > .1);
  await mobile.getByRole('button', { name: '关闭影像', exact: true }).click();
  await mobile.getByRole('tab', { name: '春日待客', exact: true }).click();
  assert(await mobile.locator('#panel-guests').isVisible());
  checks.offline_file = 'fil[本机路径已省略] entry: media playback, dialog, scene selection and zero external dependencies passed';
  assert.deepEqual(checks.console_errors, []);
  assert.deepEqual(checks.requests_failed, []);
  checks.status = 'passed';
  await writeFile(path.join(root, 'reports/verification.json'), JSON.stringify(checks, null, 2));
  console.log(JSON.stringify({ status: checks.status, desktop_media: checks.desktop_media, mobile: checks.mobile, offline_file: checks.offline_file }));
} finally {
  await browser.close();
}
