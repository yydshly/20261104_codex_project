import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('../capability-elevator/node_modules/playwright');
const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(root, 'reports/template-export');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: '[本机路径已省略] Files/Google/Chrome/Application/chrome.exe', headless: true });
const report = { story: 'Edit an existing brand template, replace local media, save/import configuration, export an independent offline page and play its media.', new_generation_credits: 0, console_errors: [], external_requests: [] };
function observe(page) {
  page.on('pageerror', error => report.console_errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) report.external_requests.push(request.url()); });
}
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true, reducedMotion: 'reduce' });
  const page = await context.newPage();
  observe(page);
  await page.goto(pathToFileURL(path.join(root, 'studio.html')).href, { waitUntil: 'load' });
  const preview = page.frameLocator('#brand-preview');
  await preview.locator('.brand-type b').waitFor();
  assert.equal(await preview.locator('.brand-type b').textContent(), '山白');
  await page.screenshot({ path: path.join(root, 'reports/studio-desktop.png') });
  await page.getByLabel('品牌名称', { exact: true }).fill('样例茶坊');
  await page.getByLabel('系列名称', { exact: true }).fill('山间来信');
  await page.getByLabel('标题第一行', { exact: true }).fill('把春山寄来，');
  await page.getByLabel('首屏介绍', { exact: true }).fill('验收文字：<春山> & “留白”\n第二行。');
  await preview.locator('.brand-type b').filter({ hasText: '样例茶坊' }).waitFor();
  assert.equal(await preview.locator('.brand-seal').textContent(), '样\n例\n茶\n坊');
  await page.getByText('配色与访问链接', { exact: true }).click();
  await page.locator('[data-field="theme.accent"]').fill('#486b57');
  await page.getByLabel('商品或咨询链接（留空则隐藏）', { exact: true }).fill('http[本机路径已省略]');
  await page.getByLabel('商品或咨询按钮文字', { exact: true }).fill('示例链接（仅验收）');
  await preview.locator('#brand-action').waitFor({ state: 'visible' });
  assert.equal(await preview.locator('#brand-action').getAttribute('href'), 'http[本机路径已省略]');
  await page.waitForFunction(() => document.getElementById('studio-status').textContent.includes('修改已预览'));
  assert.equal(await preview.locator('html').evaluate(element => element.style.getPropertyValue('--blue')), '#486b57');
  report.live_brand_and_copy = 'brand, auto-updated seal, collection, literal angle-bracket text and theme updated in preview';
  await page.locator('[data-upload="media.teapotImage"]').setInputFiles(path.join(root, 'assets/teapot.webp'));
  await page.locator('[data-asset-state="media.teapotImage"]').filter({ hasText: '已添加本地素材' }).waitFor();
  await page.locator('[data-upload="media.teapotVideo"]').setInputFiles(path.join(root, 'assets/teapot-motion.mp4'));
  await page.locator('[data-asset-state="media.teapotVideo"]').filter({ hasText: '已添加本地素材' }).waitFor();
  report.local_media = 'existing WebP and MP4 imported through real file inputs; no upload endpoint';
  await page.getByLabel('显示商品区', { exact: true }).check();
  await page.getByRole('button', { name: '导出完整网页', exact: false }).click();
  assert((await page.locator('#studio-error').textContent()).includes('商品名称'));
  assert.equal(await preview.locator('#product-section').isVisible(), false);
  await page.getByLabel('商品名称', { exact: true }).fill('验收用概念商品（非在售）');
  await page.getByLabel('规格', { exact: true }).fill('仅用于字段展示');
  await page.getByLabel('价格（包含货币单位）', { exact: true }).fill('不销售');
  await page.getByLabel('商品介绍', { exact: true }).fill('这是验收资料，使用原有茶器图检查本地图片导入，不是真实茶叶商品。');
  await page.locator('[data-upload="product.image"]').setInputFiles(path.join(root, 'assets/teapot.webp'));
  await preview.locator('#product-title').filter({ hasText: '验收用概念商品' }).waitFor();
  assert(await preview.locator('#product-section').isVisible());
  report.optional_product = 'hidden by default; export blocked without name/image; supplied test fields then rendered';
  let pending = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存配置', exact: true }).click();
  let download = await pending;
  const configFilename = download.suggestedFilename();
  const configPath = path.join(output, 'saved-config.json');
  await download.saveAs(configPath);
  const saved = JSON.parse(await readFile(configPath, 'utf8'));
  assert.equal(saved.brand.name, '样例茶坊');
  assert(saved.media.teapotImage.startsWith('data:image/webp;base64,'));
  assert(saved.media.teapotVideo.startsWith('data:video/mp4;base64,'));
  assert(saved.product.image.startsWith('data:image/webp;base64,'));
  pending = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出完整网页', exact: false }).click();
  download = await pending;
  const exportPath = path.join(output, 'standalone-export.html');
  await download.saveAs(exportPath);
  report.downloads = { configuration: configFilename, exported_page: exportPath, contains_local_media: true };
  const exported = await context.newPage();
  observe(exported);
  await exported.goto(pathToFileURL(exportPath).href, { waitUntil: 'load' });
  assert.equal(await exported.locator('.brand-type b').textContent(), '样例茶坊');
  assert.equal(await exported.locator('.hero-lead').textContent(), '验收文字：<春山> & “留白”\n第二行。');
  assert.equal(await exported.locator('#brand-action').getAttribute('href'), 'http[本机路径已省略]');
  assert(await exported.locator('#product-section').isVisible());
  assert.equal(await exported.locator('.header-actions').count(), 0);
  await exported.getByRole('button', { name: '看茶烟升起', exact: true }).click();
  await exported.waitForFunction(() => document.getElementById('dialog-film').currentTime > .1);
  assert.equal(await exported.locator('#dialog-film').evaluate(video => video.videoWidth), 1112);
  await exported.getByRole('button', { name: '关闭影像', exact: true }).click();
  report.exported_html = 'opened from a separate directory with no assets folder; replaced media plays, edited content persists, no editor controls';
  await page.locator('#preset-select').selectOption('songjian');
  await page.getByRole('button', { name: '载入示例', exact: true }).click();
  await preview.locator('.brand-type b').filter({ hasText: '松间' }).waitFor();
  await page.getByRole('button', { name: '手机', exact: true }).click();
  assert.equal(await page.locator('#brand-preview').evaluate(element => Math.round(element.getBoundingClientRect().width)), 390);
  const previewFrame = page.frames().find(frame => frame.parentFrame() === page.mainFrame());
  await previewFrame.waitForFunction(() => innerWidth === 390 && document.documentElement.scrollWidth === 390);
  await page.screenshot({ path: path.join(root, 'reports/studio-songjian.png') });
  await page.locator('#config-file').setInputFiles(configPath);
  await preview.locator('.brand-type b').filter({ hasText: '样例茶坊' }).waitFor();
  assert(await preview.locator('#product-section').isVisible());
  assert.equal(await page.getByLabel('系列名称', { exact: true }).inputValue(), '山间来信');
  report.config_round_trip = 'downloaded JSON restored brand, content, product and local media after loading another preset';
  await page.locator('#config-file').setInputFiles({ name: 'invalid-config.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ schemaVersion: 1, link: { url: 'javascript:alert(1)' } })) });
  assert((await page.locator('#studio-error').textContent()).includes('未导入'));
  assert.equal(await preview.locator('.brand-type b').textContent(), '样例茶坊');
  report.invalid_import = 'invalid action URL rejected; current edits retained';
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await mobileContext.newPage();
  observe(mobile);
  await mobile.goto(pathToFileURL(path.join(root, 'studio.html')).href, { waitUntil: 'load' });
  await mobile.frameLocator('#brand-preview').locator('.brand-type b').waitFor({ state: 'attached' });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth), 390);
  await mobile.screenshot({ path: path.join(root, 'reports/studio-mobile-edit.png') });
  await mobile.getByRole('button', { name: '查看预览', exact: true }).click();
  const phone = mobile.frameLocator('#brand-preview');
  assert(await phone.locator('#hero-title').isVisible());
  assert.equal(await phone.locator('html').evaluate(element => element.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: path.join(root, 'reports/studio-mobile-preview.png') });
  report.mobile_editor = '390px: edit/preview switches, phone preview and no horizontal overflow';
  assert.deepEqual(report.console_errors, []);
  assert.deepEqual(report.external_requests, []);
  report.status = 'passed';
  await writeFile(path.join(root, 'reports/template-verification.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ status: report.status, exported_html: report.exported_html, config_round_trip: report.config_round_trip, mobile_editor: report.mobile_editor, new_generation_credits: 0 }));
} finally { await browser.close(); }
