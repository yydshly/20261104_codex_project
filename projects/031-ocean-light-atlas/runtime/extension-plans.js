export function expansionPrompt(effect, plan) {
  const motion = !!plan.beats;
  return `${motion ? '制作一段16:9、8秒的连续镜头短片。' : '制作一张16:9的完成图。'}目标画面：${plan.target} 构图与机位：${plan.shot} ${motion ? `时间安排：0–2秒，${plan.beats[0]}；2–5秒，${plan.beats[1]}；5–8秒，${plan.beats[2]}。声音：轻微海浪与风声，无对白，声音服从画面变化。` : ''}视觉起点：${effect.name}。${plan.axis === 'transfer' ? '把参考的光影组织与纹理关系迁移到目标材质，主体以本方案描述为准。' : `${motion ? '相关阶段保留的光影特征' : '保留特征'}：${effect.criteria[0]}。`}验收重点：${plan.criteria.join('；')}。避免：${plan.avoid} 无文字、无标志。`;
}

export function expansionText(effect, plan) {
  return `${effect.number} ${effect.name} / ${plan.name}\n${plan.title}\n状态：${plan.status}\n\n目标画面：${plan.target}\n构图与机位：${plan.shot}\n交付：${plan.deliverable}\n${plan.beats ? `\n镜头计划：\n0–2秒：${plan.beats[0]}\n2–5秒：${plan.beats[1]}\n5–8秒：${plan.beats[2]}\n` : ''}\n制作步骤：\n${plan.steps.map((step,i)=>`${i+1}. ${step}`).join('\n')}\n\n验收：\n${plan.criteria.map((item,i)=>`${i+1}. ${item}`).join('\n')}\n\n避免：${plan.avoid}\n\n生成指令：\n${expansionPrompt(effect,plan)}\n\n原参考：${effect.source}\n参考作者：페빗 / PEBIT\n本内容为扩展创作方案，尚未生成对应成图或视频。`;
}
